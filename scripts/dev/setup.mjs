// Generate local-only development configuration. Does not connect to any service.
import {randomBytes} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {existsSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=fileURLToPath(new URL('../../',import.meta.url));
const state=resolve(root,'work/dev');
const fixtures=JSON.parse(readFileSync(new URL('./fixtures.json',import.meta.url),'utf8'));
const marker='# Generated by Viva Blue isolated development setup.\n';
const paths=['apps/api/.env','apps/admin/.env.local','apps/mobile/.env'];
// Preserve independently configured environments instead of silently replacing them.
for(const path of paths){
 const file=resolve(root,path);
 if(existsSync(file)&&!readFileSync(file,'utf8').startsWith(marker)){
  throw Error(`${path} already exists and is not generated development configuration. Preserve it and use the manual setup in docs/DEVELOPMENT.md.`);
 }
}
mkdirSync(state,{recursive:true,mode:0o700});
mkdirSync(resolve(state,'tls'),{recursive:true,mode:0o700});
mkdirSync(resolve(state,'keycloak/import'),{recursive:true,mode:0o700});
const secret=()=>randomBytes(32).toString('base64url');
function writePrivate(path,content){
 if(existsSync(path)&&readFileSync(path,'utf8')===content)return;
 writeFileSync(path,content,{mode:0o600});
}
const secretPath=resolve(state,'credentials.json');
const credentials=existsSync(secretPath)?JSON.parse(readFileSync(secretPath,'utf8')):{
 databaseOwnerPassword:secret(),databaseAppPassword:secret(),adminClientSecret:secret(),
 cookieSecret:secret(),keycloakAdminPassword:secret(),
 users:Object.fromEntries(fixtures.users.map(user=>[user.username,secret()]))
};
writePrivate(secretPath,JSON.stringify(credentials,null,2)+'\n');
const issuer=`https://localhost:8443/realms/${fixtures.realm}`;
const ca=resolve(state,'tls/ca.crt');
const cert=resolve(state,'tls/server.crt');
const key=resolve(state,'tls/server.key');
if(!existsSync(ca)||!existsSync(cert)||!existsSync(key)){
 const openssl=args=>execFileSync('openssl',args,{stdio:'ignore'});
 const caKey=resolve(state,'tls/ca.key');
 openssl(['req','-x509','-newkey','rsa:3072','-nodes','-days','30','-keyout',caKey,'-out',ca,
  '-subj','/CN=Viva Blue Local Development CA','-addext','basicConstraints=critical,CA:TRUE',
  '-addext','keyUsage=critical,keyCertSign,cRLSign']);
 const request=resolve(state,'tls/server.csr');
 openssl(['req','-newkey','rsa:3072','-nodes','-keyout',key,'-out',request,'-subj','/CN=localhost']);
 const extension=resolve(state,'tls/server.ext');
 writeFileSync(extension,'subjectAltName=DNS:localhost,IP:127.0.0.1\nbasicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\n');
 openssl(['x509','-req','-in',request,'-CA',ca,'-CAkey',caKey,'-CAcreateserial','-out',cert,'-days','30','-extfile',extension]);
}
const env=(path,values)=>writePrivate(resolve(root,path),marker+Object.entries(values).map(([k,v])=>`${k}=${v}`).join('\n')+'\n');
env('work/dev/database.env',{VIVABLUE_DEV_DB_PASSWORD:credentials.databaseOwnerPassword});
env('apps/api/.env',{
 NODE_ENV:'development',HOST:'127.0.0.1',PORT:4000,
 DATABASE_URL:`postgres://vivablue_app:${credentials.databaseAppPassword}@127.0.0.1:55434/vivablue_dev`,
 MIGRATION_DATABASE_URL:`postgres://vivablue_dev_owner:${credentials.databaseOwnerPassword}@127.0.0.1:55434/vivablue_dev`,
 CORS_ORIGINS:'http://localhost:3000',AUTH_ISSUER:issuer,AUTH_AUDIENCE:fixtures.audience,
 AUTH_JWKS_URL:issuer+'/protocol/openid-connect/certs',MEDIA_UPLOADS_ENABLED:'false',AWS_REGION:'us-east-1',
 VIVABLUE_DEV_SEED:'true'
});
env('apps/admin/.env.local',{
 VIVABLUE_API_ORIGIN:'http://127.0.0.1:4000',VIVABLUE_APP_ORIGIN:'http://localhost:3000',
 VIVABLUE_OIDC_ISSUER:issuer,VIVABLUE_OIDC_CLIENT_ID:'vivablue-admin-dev',
 VIVABLUE_OIDC_CLIENT_SECRET:credentials.adminClientSecret,VIVABLUE_OIDC_AUDIENCE:fixtures.audience,
 VIVABLUE_COOKIE_SECRET:credentials.cookieSecret
});
env('apps/mobile/.env',{
 EXPO_PUBLIC_API_URL:'http://localhost:4000',EXPO_PUBLIC_AUTH_ISSUER:issuer,
 EXPO_PUBLIC_AUTH_CLIENT_ID:'vivablue-mobile-dev',EXPO_PUBLIC_AUTH_AUDIENCE:fixtures.audience,
 EXPO_PUBLIC_DEMO_GALLERY:'false'
});
const audienceMapper={name:'salon-api-audience',protocol:'openid-connect',protocolMapper:'oidc-audience-mapper',
 config:{'included.custom.audience':fixtures.audience,'access.token.claim':'true','id.token.claim':'false'}};
const realm={realm:fixtures.realm,enabled:true,displayName:'Viva Blue LOCAL TEST identity provider',
 sslRequired:'all',registrationAllowed:true,registrationEmailAsUsername:false,resetPasswordAllowed:false,
 verifyEmail:false,loginWithEmailAllowed:true,accessTokenLifespan:300,ssoSessionIdleTimeout:1800,
 revokeRefreshToken:true,refreshTokenMaxReuse:0,
 clients:[
  {clientId:'vivablue-mobile-dev',name:'Local development mobile',protocol:'openid-connect',publicClient:true,
   standardFlowEnabled:true,directAccessGrantsEnabled:false,implicitFlowEnabled:false,
   redirectUris:['vivablue://auth/callback'],webOrigins:[],defaultClientScopes:['basic','profile','email'],optionalClientScopes:['offline_access'],
   attributes:{'pkce.code.challenge.method':'S256'},protocolMappers:[audienceMapper]},
  {clientId:'vivablue-admin-dev',name:'Local development admin',protocol:'openid-connect',publicClient:false,
   secret:credentials.adminClientSecret,standardFlowEnabled:true,directAccessGrantsEnabled:false,implicitFlowEnabled:false,
   redirectUris:['http://localhost:3000/api/auth/callback'],webOrigins:['http://localhost:3000'],
   defaultClientScopes:['basic','profile','email'],attributes:{'pkce.code.challenge.method':'S256'},protocolMappers:[audienceMapper]},
  {clientId:'vivablue-browser-test',name:'Local protocol test client (not the mobile app)',protocol:'openid-connect',publicClient:true,
   standardFlowEnabled:true,directAccessGrantsEnabled:false,implicitFlowEnabled:false,
   redirectUris:['http://localhost:8089/callback'],webOrigins:[],
   defaultClientScopes:['basic','profile','email'],optionalClientScopes:['offline_access'],
   attributes:{'pkce.code.challenge.method':'S256'},protocolMappers:[audienceMapper]}
 ],
 users:fixtures.users.map(user=>({id:user.id,username:user.username,enabled:true,emailVerified:true,
  firstName:'Development',lastName:user.role,email:user.username+'@example.invalid',requiredActions:[],
  realmRoles:['offline_access'],
  credentials:[{type:'password',value:credentials.users[user.username],temporary:false}]}))
};
writePrivate(resolve(state,'keycloak/import/vivablue-dev-realm.json'),JSON.stringify(realm,null,2)+'\n');
console.log('Generated isolated development configuration; credentials are private in work/dev/credentials.json.');
console.log('Existing generated credentials and data are retained on repeat setup. No services or migrations were started.');
console.log('Local TLS CA: work/dev/tls/ca.crt (generated with 30-day validity; local test use only).');
